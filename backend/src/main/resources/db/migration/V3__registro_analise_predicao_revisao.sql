-- V3: núcleo de análise (registro, predição e revisão humana).

CREATE TABLE registro_analise (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id            BIGINT      NOT NULL REFERENCES usuario (id),

    faixa_etaria          VARCHAR(5),
    estado_civil          INTEGER,
    escolaridade          INTEGER,
    tipo_gravidez         INTEGER,

    gestacoes_anteriores  INTEGER NOT NULL,
    partos_normais        INTEGER NOT NULL,
    partos_cesareos       INTEGER NOT NULL,
    filhos_vivos          INTEGER NOT NULL,
    perdas_fetais         INTEGER NOT NULL,

    mes_pre_natal         INTEGER,
    criado_em             TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT ck_registro_faixa_etaria CHECK (
        faixa_etaria IS NULL OR faixa_etaria IN (
            '10-14', '15-19', '20-24', '25-29', '30-34',
            '35-39', '40-44', '45-49', '>=50'
        )
    ),

    CONSTRAINT ck_registro_estado_civil CHECK (
        estado_civil IS NULL OR estado_civil BETWEEN 1 AND 5 OR estado_civil = 9
    ),

    CONSTRAINT ck_registro_escolaridade CHECK (
        escolaridade IS NULL OR escolaridade BETWEEN 0 AND 5 OR escolaridade = 9
    ),

    CONSTRAINT ck_registro_tipo_gravidez CHECK (
        tipo_gravidez IS NULL OR tipo_gravidez BETWEEN 1 AND 3 OR tipo_gravidez = 9
    ),

    CONSTRAINT ck_registro_gestacoes CHECK (
        gestacoes_anteriores BETWEEN 0 AND 15
    ),

    CONSTRAINT ck_registro_partos_normais CHECK (
        partos_normais BETWEEN 0 AND 15
    ),

    CONSTRAINT ck_registro_partos_cesareos CHECK (
        partos_cesareos BETWEEN 0 AND 15
    ),

    CONSTRAINT ck_registro_filhos_vivos CHECK (
        filhos_vivos BETWEEN 0 AND 15
    ),

    CONSTRAINT ck_registro_perdas_fetais CHECK (
        perdas_fetais BETWEEN 0 AND 15
    ),

    CONSTRAINT ck_registro_soma_partos CHECK (
        partos_normais + partos_cesareos <= gestacoes_anteriores
    ),

    CONSTRAINT ck_registro_mes_pre_natal CHECK (
        mes_pre_natal IS NULL OR mes_pre_natal BETWEEN 1 AND 9
    )
);

CREATE INDEX idx_registro_analise_usuario
    ON registro_analise (usuario_id);

CREATE TABLE predicao (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registro_analise_id   BIGINT           NOT NULL REFERENCES registro_analise (id),
    usuario_id            BIGINT           NOT NULL REFERENCES usuario (id),
    score                 DOUBLE PRECISION NOT NULL,
    faixa_risco           VARCHAR(10)      NOT NULL,
    fatores_shap          JSONB            NOT NULL,
    versao_modelo         VARCHAR(40)      NOT NULL,
    criado_em             TIMESTAMPTZ      NOT NULL DEFAULT now(),

    CONSTRAINT ck_predicao_score
        CHECK (score >= 0 AND score <= 1),

    CONSTRAINT ck_predicao_faixa
        CHECK (faixa_risco IN ('BAIXO', 'MEDIO', 'ALTO'))
);

CREATE INDEX idx_predicao_registro
    ON predicao (registro_analise_id, criado_em DESC);

CREATE INDEX idx_predicao_usuario
    ON predicao (usuario_id);

CREATE INDEX idx_predicao_faixa_criado_em
    ON predicao (faixa_risco, criado_em);

CREATE TABLE revisao_humana (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    predicao_id    BIGINT       NOT NULL REFERENCES predicao (id),
    solicitante_id BIGINT       NOT NULL REFERENCES usuario (id),
    status         VARCHAR(15)  NOT NULL DEFAULT 'PENDENTE',
    solicitado_em  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    revisor_id     BIGINT       REFERENCES usuario (id),
    parecer        TEXT,
    concluida_em   TIMESTAMPTZ,

    CONSTRAINT ck_revisao_status
        CHECK (status IN ('PENDENTE', 'CONCLUIDA')),

    CONSTRAINT ck_revisao_coerencia CHECK (
        (status = 'PENDENTE' AND revisor_id IS NULL AND concluida_em IS NULL)
        OR
        (status = 'CONCLUIDA' AND revisor_id IS NOT NULL AND concluida_em IS NOT NULL)
    )
);

CREATE INDEX idx_revisao_predicao
    ON revisao_humana (predicao_id);

CREATE INDEX idx_revisao_status
    ON revisao_humana (status);

CREATE UNIQUE INDEX uq_revisao_pendente
    ON revisao_humana (predicao_id)
    WHERE status = 'PENDENTE';