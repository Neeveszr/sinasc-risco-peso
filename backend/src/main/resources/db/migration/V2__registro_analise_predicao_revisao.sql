-- V2: núcleo de análise (registro, predição e revisão humana).

CREATE TABLE registro_analise (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT      NOT NULL REFERENCES usuario (id),
    criado_em   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_registro_analise_usuario
    ON registro_analise (usuario_id);

CREATE TABLE predicao (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registro_analise_id  BIGINT           NOT NULL REFERENCES registro_analise (id),
    usuario_id           BIGINT           NOT NULL REFERENCES usuario (id),
    probabilidade        DOUBLE PRECISION NOT NULL,
    faixa_risco          VARCHAR(10)      NOT NULL,
    fatores_shap         JSONB            NOT NULL,
    versao_modelo        VARCHAR(40)      NOT NULL,
    criado_em            TIMESTAMPTZ      NOT NULL DEFAULT now(),

    CONSTRAINT ck_predicao_probabilidade
        CHECK (probabilidade >= 0 AND probabilidade <= 1),

    CONSTRAINT ck_predicao_faixa
        CHECK (faixa_risco IN ('BAIXO', 'MEDIO', 'ALTO'))
);

CREATE INDEX idx_predicao_registro
    ON predicao (registro_analise_id, criado_em DESC);

CREATE INDEX idx_predicao_usuario
    ON predicao (usuario_id);

CREATE INDEX idx_predicao_faixa_criado_em
    ON predicao (faixa_risco, criado_em);

CREATE TABLE revisao_humana (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    predicao_id    BIGINT       NOT NULL REFERENCES predicao (id),
    solicitante_id BIGINT       NOT NULL REFERENCES usuario (id),
    status         VARCHAR(15)  NOT NULL DEFAULT 'PENDENTE',
    solicitado_em  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    revisor_id     BIGINT       REFERENCES usuario (id),
    parecer        TEXT,
    concluida_em   TIMESTAMPTZ,

    CONSTRAINT ck_revisao_status
        CHECK (status IN ('PENDENTE', 'CONCLUIDA')),

    CONSTRAINT ck_revisao_coerencia CHECK (
        (status = 'PENDENTE' AND revisor_id IS NULL AND concluida_em IS NULL)
        OR
        (status = 'CONCLUIDA' AND revisor_id IS NOT NULL AND concluida_em IS NOT NULL)
    )
);

CREATE INDEX idx_revisao_predicao
    ON revisao_humana (predicao_id);

CREATE INDEX idx_revisao_status
    ON revisao_humana (status);
